"""Master data for the fictional manufacturer: items, inventory, customers, contacts, ship-to sites, cross-references.
Generated by script (not hand-typed) with a fixed seed so every run is reproducible."""
import random
from .db import audit

FAMILIES = {  # prefix: (description, base price)
    "HF": ("Hydraulic fitting", 4.20), "HA": ("Hose assembly", 38.00), "BV": ("Ball valve", 12.50),
    "PG": ("Pressure gauge", 21.00), "QC": ("Quick coupling", 9.80), "AD": ("Thread adapter", 3.10), "SK": ("Seal kit", 14.75),
}
SIZES = {"0412": ('1/4" x 1/2"', 1.0), "0634": ('3/8" x 3/4"', 1.35), "0834": ('1/2" x 3/4"', 1.8), "1012": ('5/8" x 1"', 2.4)}
MATS = {"SS": ("stainless", 1.6), "BR": ("brass", 1.0), "CS": ("carbon steel", 0.8)}
MOQ_PACK = [(1, 1), (1, 1), (5, 5), (10, 10), (10, 5)]

COMPANIES = ["Brightwater Hydraulics", "Cascade Equipment Co", "Dunmore Industrial Supply", "Eastgate Fluid Power", "Fairview Machine Works",
             "Granite State Pumps", "Harlow Mobile Equipment", "Ironbridge Fabrication", "Juniper Ag Systems", "Keystone Mining Services",
             "Lakeshore Marine Repair", "Meridian Packaging", "Northgate Tool & Die", "Oakmont Food Processing", "Prairie Wind Energy",
             "Quarry Ridge Aggregates", "Redline Truck Bodies", "Summit Rail Services", "Tidewater Shipyards", "Upland Forestry Equipment",
             "Valley Press & Stamping", "Westbrook Concrete", "Xenia Plastics", "Yardley Waste Systems", "Zephyr HVAC Controls",
             "Alder Creek Sawmill", "Blue Heron Dredging", "Copperline Wire & Cable", "Delta Ridge Irrigation", "Evergreen Paper Mills"]
CITIES = [("Dayton", "OH", "45402"), ("Tulsa", "OK", "74103"), ("Erie", "PA", "16501"), ("Reno", "NV", "89501"), ("Duluth", "MN", "55802"),
          ("Mobile", "AL", "36602"), ("Boise", "ID", "83702"), ("Akron", "OH", "44308"), ("Wichita", "KS", "67202"), ("Spokane", "WA", "99201"),
          ("Tampa", "FL", "33602"), ("Fresno", "CA", "93721"), ("Omaha", "NE", "68102"), ("Albany", "NY", "12207"), ("Mesa", "AZ", "85201")]
FIRST = ["sam", "jordan", "alex", "casey", "morgan", "riley", "taylor", "drew", "jamie", "chris"]


def slug(name):
    return "".join(c for c in name.lower().split()[0] if c.isalnum())


def build(db, seed=42):
    rng = random.Random(seed)
    # ---- items + inventory
    n = 0
    for fam, (fdesc, base) in FAMILIES.items():
        for size, (sdesc, sf) in SIZES.items():
            for mat, (mdesc, mf) in MATS.items():
                if rng.random() < 0.72:                       # not every combination exists
                    sku = f"{fam}-{size}-{mat}"
                    moq, pack = rng.choice(MOQ_PACK)
                    db.execute("INSERT INTO items VALUES (?,?,?,?,?,?)",
                               (sku, f"{fdesc} {sdesc} {mdesc}", "EA", round(base * sf * mf, 2), moq, pack))
                    on_hand = rng.choice([0, 12, 40, 150, 400, 800, 1200, 1200])
                    db.execute("INSERT INTO inventory VALUES (?,?,?)", (sku, on_hand, min(on_hand, rng.randint(0, 30))))
                    n += 1
    skus = [r["sku"] for r in db.execute("SELECT sku FROM items")]

    # ---- customers
    for i, name in enumerate(COMPANIES, 1):
        acct = f"C-{1000 + i}"
        limit = rng.choice([25000, 50000, 80000, 120000, 250000])
        db.execute("INSERT INTO customers(id,account_no,name,email_domain,credit_limit,balance,credit_hold,discount_pct,requires_po,default_ship_code) "
                   "VALUES (?,?,?,?,?,?,?,?,?,?)",
                   (i, acct, name, f"{slug(name)}.example", limit, round(limit * rng.uniform(0.05, 0.45), 2), 0,
                    rng.choice([0, 0, 0.05, 0.08, 0.12]), 0 if i % 11 == 0 else 1, None))
        for j in range(rng.choice([1, 2, 3])):
            email = f"{FIRST[(i + j) % len(FIRST)]}.{slug(name)}@{slug(name)}.example"
            db.execute("INSERT OR IGNORE INTO contacts VALUES (?,?,?)", (email, i, f"{FIRST[(i + j) % len(FIRST)].title()} {name.split()[0]}"))
        sites = rng.sample(CITIES, rng.choice([1, 1, 2, 3]))
        for k, (city, st, zp) in enumerate(sites, 1):
            code = f"S{k:02d}"
            db.execute("INSERT INTO ship_to(customer_id,code,address,city,state,zip) VALUES (?,?,?,?,?,?)",
                       (i, code, f"{rng.randint(100, 9800)} {rng.choice(['Industrial Pkwy', 'Commerce Dr', 'Foundry Rd', 'Mill St', 'Harbor Way'])}", city, st, zp))
        if len(sites) > 1 and i % 2 == 0:                      # half of the multi-site customers have a default
            db.execute("UPDATE customers SET default_ship_code='S01' WHERE id=?", (i,))
        if i % 3 == 0:                                         # customer-specific part numbers
            for sku in rng.sample(skus, 5):
                db.execute("INSERT INTO customer_xref VALUES (?,?,?)", (i, f"{slug(name).upper()[:5]}-{rng.randint(10, 99)}-{rng.randint(1000, 9999)}", sku))
    # ---- deliberate account conditions used by the demo
    db.execute("UPDATE customers SET credit_hold=1 WHERE id IN (7, 19)")
    db.execute("UPDATE customers SET balance=credit_limit-400 WHERE id IN (13, 25)")
    audit(db, "system", "seed_master_data", "", f"{n} items, {len(COMPANIES)} customers")
    db.commit()
